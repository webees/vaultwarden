#!/bin/bash
# ╔═══════════════════════════════════════════════════════════════════════════╗
# ║ Restic Backup Script                                                      ║
# ╚═══════════════════════════════════════════════════════════════════════════╝
# Usage: /restic.sh {backup|audit|check-freshness|check-disk|notify-test|restore <id>|restore-test [id]|snapshots|verify}
#        `restore <id>` overwrites the live /data and needs RESTORE_CONFIRM=yes.

set -uo pipefail

COMMAND="${1:-}"
READ_ONLY_AUDIT=false
if [ "$COMMAND" = "audit" ]; then
    READ_ONLY_AUDIT=true
fi

# Run as the unprivileged owner so files created here never become root-owned.
# `fly ssh console` starts as root; without this, cleans before forever.
if [ "$(id -u)" = "0" ] && command -v su-exec >/dev/null 2>&1; then
    exec su-exec vaultwarden:vaultwarden "$0" "$@"
fi

# The run logs and the status file carry the repository's own output, so they
# stay private to their owner whichever umask the caller had: `fly ssh console`
# starts as root with 022, which used to leave world-readable logs next to the
# 0600 ones the scheduler wrote.
umask 077

# ── Configuration ─────────────────────────────────────────────────────────────
APP_NAME="${FLY_APP_NAME:-Vaultwarden}"
DATA="/data"
LOG_DIR="${RESTIC_LOG_DIR:-/data/restic-logs}"
LOG="$LOG_DIR/$(date +%Y%m%d_%H%M%S).log"
MAX_LOG_BYTES="${RESTIC_LOG_MAX_BYTES:-262144}"
MAX_LOG_DIR_BYTES="${RESTIC_LOG_DIR_MAX_BYTES:-10485760}"
QUICK_TIMEOUT="${RESTIC_QUICK_TIMEOUT:-60}"
LONG_TIMEOUT="${RESTIC_LONG_TIMEOUT:-1800}"
# Configuration is untrusted even when it comes from an operator. Keep the
# values accepted by this root-adjacent maintenance path inside ranges that
# cannot overflow shell arithmetic or turn the bounded capture into a disk-fill
# primitive. The defaults are far below these ceilings.
LIMIT_LOG_BYTES=8388608
LIMIT_LOG_DIR_BYTES=67108864
LIMIT_QUICK_TIMEOUT=3600
LIMIT_LONG_TIMEOUT=86400
LIMIT_BACKUP_AGE=31536000
NOTIFY_ON_SUCCESS="${BACKUP_NOTIFY_ON_SUCCESS:-false}"
TELEGRAM_BOT_TOKEN="${TELEGRAM_BOT_TOKEN:-}"
TELEGRAM_CHAT_ID="${TELEGRAM_CHAT_ID:-}"
STATUS_FILE="/data/backup-status.txt"
MAX_STATUS_BYTES=4096
# SQLite reports some integrity failures as result rows with a successful exit
# status. Treat "ok" as the complete output contract, not merely one line that
# may be present among diagnostics.
# shellcheck disable=SC2016  # AWK fields expand inside the child, not here.
SQLITE_INTEGRITY_AWK='
NR == 1 && $0 == "ok" { valid = 1; next }
{ print; invalid = 1 }
END {
    if (NR == 0) print "PRAGMA integrity_check returned no result"
    if (NR != 1 || !valid || invalid) exit 1
}
'

is_regular_file() {
    [ ! -L "$1" ] && [ -f "$1" ]
}

# The marker is generated by this script and should stay far below this cap.
# Read at most one byte beyond the limit, with a non-newline sentinel so command
# substitution cannot hide trailing newlines, then reject the file as a whole.
read_status_body() {
    local snapshot
    is_regular_file "$STATUS_FILE" || return 4
    snapshot="$( { head -c "$((MAX_STATUS_BYTES + 1))" "$STATUS_FILE" 2>/dev/null \
        && printf '\001'; } )" || return 1
    snapshot="${snapshot%$'\001'}"
    [ "${#snapshot}" -le "$MAX_STATUS_BYTES" ] || return 3
    printf '%s' "$snapshot"
}

# Read the marker once and keep its outcomes distinct. An ignored pipeline used
# to turn an unreadable file, a missing field, and a fresh volume all into
# last_success=0, so the guard could report the wrong cause and replace the
# evidence with a synthetic marker. `check-freshness` alerts on any read or
# schema failure, while only an actually absent marker means "no data yet".
STATUS_STATE=""
STATUS_MARKER_ERROR=""
LAST_SUCCESS=0
if [ -e "$STATUS_FILE" ]; then
    if status_body="$(read_status_body)"; then
        STATUS_STATE="$(printf '%s\n' "$status_body" | sed -n 's/^state=//p' | head -n 1)"
        LAST_SUCCESS="$(printf '%s\n' "$status_body" | sed -n 's/^last_success=//p' | head -n 1)"
        case "${LAST_SUCCESS:-}" in
            '') STATUS_MARKER_ERROR=missing; LAST_SUCCESS=0 ;;
            *[!0-9]*) STATUS_MARKER_ERROR=invalid; LAST_SUCCESS=0 ;;
            *)
                # Bash arithmetic wraps anything above signed 64-bit. A
                # syntactically numeric marker must not become a fresh backup
                # after overflow, and a leading zero must not silently switch
                # the timestamp to octal.
                if [ "${#LAST_SUCCESS}" -gt 18 ]; then
                    STATUS_MARKER_ERROR=invalid
                    LAST_SUCCESS=0
                else
                    LAST_SUCCESS=$((10#$LAST_SUCCESS))
                fi
                ;;
        esac
    else
        read_rc=$?
        case "$read_rc" in
            3) STATUS_MARKER_ERROR=oversized ;;
            4) STATUS_MARKER_ERROR=not_regular ;;
            *) STATUS_MARKER_ERROR=unreadable ;;
        esac
    fi
fi
CURRENT_STEP=""

# Diagnostics can repeat whatever the backend sent on stderr. Never persist a
# configured credential or private endpoint verbatim in a run log. Keep longer
# values too: the exact repository URL, mail recipient and host names are
# personal infrastructure data even when they are not authentication secrets.
SENSITIVE_VALUES=()
add_sensitive_value() {
    local value="${1:-}" existing
    [ -n "$value" ] || return 0
    if [ "${#SENSITIVE_VALUES[@]}" -gt 0 ]; then
        for existing in "${SENSITIVE_VALUES[@]}"; do
            [ "$existing" = "$value" ] && return 0
        done
    fi
    SENSITIVE_VALUES+=("$value")
}
# NUL-delimited records keep a newline-containing secret in one value.
while IFS= read -r -d '' record; do
    case "$record" in
        *=*) ;;
        *) continue ;;
    esac
    name="${record%%=*}"
    value="${record#*=}"
    case "$name" in
        *_PASSWORD|*_TOKEN|*_SECRET|*_PRIVATE_KEY|*_API_KEY|\
        AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY|\
        RESTIC_REPOSITORY|SMTP_HOST|SMTP_USERNAME|SMTP_FROM|SMTP_TO|\
        ORG_CREATION_USERS|TELEGRAM_CHAT_ID|HEALTHCHECK_URL|CADDY_DOMAINS|\
        DOMAIN|FLY_APP_NAME)
            add_sensitive_value "$value"
            ;;
    esac
done < <(env -0)

# ANSI colors
R="\x1b[31;01m" G="\x1b[32;01m" Y="\x1b[33;01m" B="\x1b[34;01m" X="\x1b[0m"

# ── Utilities ─────────────────────────────────────────────────────────────────

redact_raw() {
    local body="$1" value
    if [ "${#SENSITIVE_VALUES[@]}" -gt 0 ]; then
        for value in "${SENSITIVE_VALUES[@]}"; do
            body="${body//"$value"/<redacted>}"
        done
    fi
    # `restic snapshots` prints the snapshot ID in the first table column and
    # the machine hostname in a later column. A Fly host is a long hexadecimal
    # identifier, while the user-facing snapshot ID is eight characters. Keep
    # the latter readable and remove the former before any output is persisted.
    printf '%s' "$body" | sed -E \
        '/^[[:space:]]*[0-9a-fA-F]{8}[[:space:]]/ s/([[:space:]])[0-9a-fA-F]{12,}([[:space:]]|$)/\1[redacted-fly-machine-host]\2/g'
}

redact_file() {
    local body
    body="$(cat "$1")" || return 2
    redact_raw "$body"
}

# Log output to file and stdout. Both paths carry the same bounded, redacted
# text so a diagnostic can never expose a credential that was present in the
# process environment.
log() {
    local body redacted
    body="$("$@" 2>&1)"
    redacted="$(redact_raw "$body")"
    if [ -n "$redacted" ]; then
        if [ "$READ_ONLY_AUDIT" = true ]; then
            printf '%s\n' "$redacted"
        else
            printf '%s\n' "$redacted" | tee -a "$LOG"
        fi
    fi
    return 0
}

# A successful visible command adds log framing without losing its real exit
# status. Pipes inherit the redaction above instead of streaming raw output.
log_result() {
    local status="${1:-0}"
    shift
    log "$@"
    return "$status"
}

# Persist a small freshness marker for local monitoring
write_status() {
    local state="$1" message="${2:-}" now tmp
    now="$(date -u +%s)"
    tmp="${STATUS_FILE}.tmp.$$"
    local body
    printf -v body 'state=%s\nupdated_at=%s\nlast_success=%s\nmessage=%s\n' \
        "$state" "$now" "$LAST_SUCCESS" "$message"
    # Atomic rename when the log volume is writable, in-place fallback otherwise
    if ! [ -d "$STATUS_FILE" ] \
        && printf '%s' "$body" > "$tmp" \
        && mv "$tmp" "$STATUS_FILE"; then
        return 0
    fi
    rm -f "$tmp" || echo "Warning: cannot remove ${tmp}" >&2
    if printf '%s' "$body" > "$STATUS_FILE"; then
        return 0
    fi
    echo "Error: cannot write ${STATUS_FILE}; backup state was not recorded" >&2
    return 1
}

# The volume guard and the monthly verify are not backup runs, and `state` is the
# backup job's in-flight marker: `check-freshness` reads `state=running` to tell
# a backup that started but never finished. The guard at :35 used to overwrite
# that marker before the check at :45 could read it, which replaced the
# immediate "did not finish" alert with a much later stale-backup one. Keep the
# marker and carry the guard's own alert in the message instead.
write_guard_status() {
    local state="$1" message="$2" current current_body
    current=""
    if current_body="$(read_status_body)"; then
        current="$(printf '%s\n' "$current_body" | sed -n 's/^state=//p' | head -n 1)"
    fi
    if [ "$current" = "running" ]; then
        write_status running "${message} (backup in flight)"
    else
        write_status "$state" "$message"
    fi
}

# Optional dead-man's-switch ping (e.g. healthchecks.io). No-op when HEALTHCHECK_URL is unset.
heartbeat() {
    [ -z "${HEALTHCHECK_URL:-}" ] && return 0
    local suffix=""
    [ "${1:-ok}" = "fail" ] && suffix="/fail"
    curl -fsS -m 10 --retry 3 "${HEALTHCHECK_URL}${suffix}" >/dev/null 2>&1 \
        || log echo -e "${Y}Heartbeat ping failed${X}"
}

# Log an error and abort; used when the scratch files below cannot be created.
die() { log echo -e "${R}$1${X}"; exit 2; }

# Reject misconfigured limits instead of clearing every log file, constructing
# an invalid tail size, or timing out every restic command without saying why.
# Only canonical decimal integers are accepted so later arithmetic cannot hit
# octal parsing or an overflowing signed shell integer.
require_bounded_int() {
    local name="$1" value="${2:-}" maximum="$3"
    case "$value" in
        [1-9]*) ;;
        *)
            echo "Error: ${name} must be between 1 and ${maximum}, got '${value}'" >&2
            exit 2
            ;;
    esac
    case "$value" in
        *[!0-9]*)
            echo "Error: ${name} must be between 1 and ${maximum}, got '${value}'" >&2
            exit 2
            ;;
    esac
    if [ "${#value}" -gt "${#maximum}" ] \
        || { [ "${#value}" -eq "${#maximum}" ] && [ "$value" -gt "$maximum" ]; }; then
        echo "Error: ${name} must be between 1 and ${maximum}, got '${value}'" >&2
        exit 2
    fi
}

# Run a command under a hard timeout and then signal whatever it left behind.
# BusyBox `timeout` reaches its direct child only, so a helper the command
# spawned outlives it: the helper holds a captured pipe open, which makes the
# run outlive its own timeout, and a lock it inherited never clears. `setsid`
# puts the tree in a session of its own so the group signal below reaches it,
# and the subshell keeps the backup lock out of the command's hands - a child
# that outlives the run would hold it forever, and every later backup would
# exit 3 as a "concurrent run", an exit that is deliberately not alerted.
stop_process_group() {
    local pid="$1" attempt=0
    kill -TERM -"$pid" 2>/dev/null || return 0
    while kill -0 -"$pid" 2>/dev/null; do
        if [ "$attempt" -ge 10 ]; then
            # A helper is allowed to clean up for one second. Ignoring TERM
            # cannot leave it holding the captured pipe or the backup lock.
            kill -KILL -"$pid" 2>/dev/null || :
            break
        fi
        sleep 0.1
        attempt=$((attempt + 1))
    done
    return 0
}

timed() {
    local seconds="$1"
    shift
    (
        exec 9>&-
        setsid timeout -k 30 "$seconds" "$@" &
        timed_pid=$!
        wait "$timed_pid"
        timed_rc=$?
        stop_process_group "$timed_pid"
        exit "$timed_rc"
    )
}

# Remove locks left behind by a run that was killed mid-flight. restic keeps
# locks whose process is still alive, so this cannot disturb a running backup,
# but without it one interrupted run makes verify/restore fail with "repository
# is already locked" until the next hourly backup happens to clear it.
clear_stale_locks() {
    # A failed cleanup leaves the lock state unknown. Route it through `run` so
    # the backend's error is retained and the caller stops before its real
    # repository operation; silently continuing can act on a still-locked repo.
    run "Clear stale repository locks" "$QUICK_TIMEOUT" restic unlock
}

# Whether another run holds the backup lock, as three states:
#   0 a run holds it, 1 nobody holds it, 2 it cannot be inspected.
# A read-only open avoids creating the lock file, and "cannot inspect" must not
# be collapsed into "not running": that turns a live backup into a false alert.
backup_is_running() {
    is_regular_file "$LOG_DIR/backup.lock" || return 2
    exec 8<"$LOG_DIR/backup.lock" 2>/dev/null || return 2
    if flock -n 8; then
        exec 8>&-
        return 1
    fi
    exec 8>&-
    return 0
}

# Send email notification; the timeout keeps a stalled SMTP relay from blocking the run.
send_mail() {
    [ -z "${SMTP_TO:-}" ] && return 0
    # Strip ANSI colors and set UTF-8. The outcome is written to the log so
    # "the alert never arrived" can be diagnosed from the run itself instead of
    # from whatever the mailer happened to print on stderr.
    local out_file rc
    out_file="$(mktemp "${TMPDIR:-/tmp}/restic-mail.XXXXXX")"
    if [ -z "$out_file" ]; then
        log echo -e "${R}Alert email failed (cannot record transport output)${X}"
        return 1
    fi
    # Keep relay output off the shell heap and persist only a bounded tail.
    (
        exec 9>&-
        sed 's/\x1b\[[0-9;]*m//g' "$LOG" | timeout 45 mail \
            -a "Content-Type: text/plain; charset=UTF-8" \
            -s "[$APP_NAME] $1" "$SMTP_TO" 2>&1 \
            | tail -c "$MAX_LOG_BYTES" > "$out_file"
    )
    rc=$?
    if [ "$rc" -eq 0 ]; then
        log echo -e "${G}Alert email sent${X}"
    else
        log echo -e "${R}Alert email failed (exit ${rc})${X}"
        if [ -s "$out_file" ]; then
            log redact_file "$out_file"
        fi
    fi
    if ! rm -f "$out_file"; then
        log echo -e "${Y}Warning: cannot remove mailer output file${X}"
        return 1
    fi
    [ "$rc" -eq 0 ] && return 0
    return 1
}

# Send a short Telegram notification through the Bot API. The token and chat id
# are secrets: the request contains them, but the persistent run log must not.
send_telegram() {
    [ -z "${TELEGRAM_BOT_TOKEN:-}" ] && return 0
    local text="$1" out rc status body status_file tail_rc
    status_file="$(mktemp "${TMPDIR:-/tmp}/restic-telegram-status.XXXXXX")"
    if [ -z "$status_file" ]; then
        log echo -e "${R}Telegram notification failed (cannot record transport status)${X}"
        return 1
    fi
    if ! exec 3>"$status_file"; then
        rm -f "$status_file" \
            || log echo -e "${Y}Warning: cannot remove Telegram status file${X}"
        log echo -e "${R}Telegram notification failed (cannot record transport status)${X}"
        return 1
    fi
    # No --fail on purpose: the API answers a rejection with its own explanation,
    # and --fail discards that body, so the run log kept "exit 22" as the only
    # clue. Success is read from the body below, so a 4xx cannot pass as sent.
    # Only the bounded response reaches memory; the temporary file carries the
    # numeric transport status and never any response content or credentials.
    out="$(
        {
            curl -sS -m 10 --retry 2 \
                -w '\n%{http_code}' \
                --data-urlencode "chat_id=${TELEGRAM_CHAT_ID}" \
                --data-urlencode "text=[$APP_NAME] ${text}" \
                --data-urlencode "disable_web_page_preview=true" \
                "https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}/sendMessage" 2>&1
            printf '%s\n' "$?" >&3
        } | tail -c "$MAX_LOG_BYTES"
    )"
    tail_rc=$?
    exec 3>&-
    if [ "$tail_rc" -ne 0 ] || ! rc="$(cat "$status_file")"; then
        rm -f "$status_file" \
            || log echo -e "${Y}Warning: cannot remove Telegram status file${X}"
        log echo -e "${R}Telegram notification failed (cannot record response)${X}"
        return 1
    fi
    if ! rm -f "$status_file"; then
        log echo -e "${Y}Warning: cannot remove Telegram status file${X}"
        return 1
    fi
    # curl appends the HTTP status after the body; keep them apart so a JSON
    # error body is not mistaken for the transport result.
    status="${out##*$'\n'}"
    body="${out%$'\n'*}"
    if [ "$rc" -eq 0 ] && [ "$status" = "200" ] \
        && printf '%s\n' "$body" | grep -q '"ok"[[:space:]]*:[[:space:]]*true'; then
        log echo -e "${G}Telegram notification sent${X}"
        return 0
    fi
    # `exit 0` here used to mean "curl reached the API and the API said no",
    # which read like success. Name the HTTP status instead, and keep the curl
    # exit code only for a transport failure.
    if [ "$rc" -ne 0 ]; then
        log echo -e "${R}Telegram notification failed (curl exit ${rc})${X}"
    elif [ -n "$status" ] && [ "$status" != "000" ]; then
        log echo -e "${R}Telegram notification failed (HTTP ${status})${X}"
    else
        log echo -e "${R}Telegram notification failed (no HTTP response)${X}"
    fi
    # Record whatever came back — the API's error body or curl's own message —
    # with both credentials redacted. A proxy error page can echo the token URL,
    # while the Bot API identifies the rejected chat by its id.
    body="${body//$TELEGRAM_BOT_TOKEN/<redacted>}"
    [ -n "$TELEGRAM_CHAT_ID" ] && body="${body//$TELEGRAM_CHAT_ID/<redacted>}"
    [ -n "$body" ] && log printf '%s\n' "$body"
    return 1
}

# The rare channel: email and Telegram. A job that runs every hour would repeat
# this alert up to 24 times a day, so the hourly jobs ping Telegram only and
# keep this for the monthly integrity check. Each channel is optional.
notify_rare() {
    local subject="$1" mail_rc=0 telegram_rc=0
    send_mail "$subject" || mail_rc=$?
    send_telegram "$subject" || telegram_rc=$?
    [ "$mail_rc" -eq 0 ] && [ "$telegram_rc" -eq 0 ]
}

# Exercise both rare-alert transports without touching backup state. This is a
# manual production diagnostic: a configured channel that rejects the message
# must fail the command, so a green run proves both deliveries were accepted.
notify_test() {
    local failed=""
    [ -n "${SMTP_TO:-}" ] || failed="SMTP_TO is not configured"
    if [ -z "${TELEGRAM_BOT_TOKEN:-}" ] || [ -z "${TELEGRAM_CHAT_ID:-}" ]; then
        failed="${failed:+${failed}; }TELEGRAM_BOT_TOKEN and TELEGRAM_CHAT_ID must both be configured"
    fi
    if [ -n "$failed" ]; then
        log echo -e "${R}Notification test cannot run: ${failed}${X}"
        return 2
    fi
    if notify_rare "Notification test"; then
        log echo -e "${G}Notification test passed${X}"
        return 0
    fi
    log echo -e "${R}Notification test failed${X}"
    return 1
}

# Warn when the audit trail cannot be written: a run with no log file and no
# status file is invisible to whoever has to diagnose it later.
check_audit_trail() {
    if ! ( : >> "$LOG" ) 2>/dev/null; then
        echo "Warning: cannot write ${LOG}; this run leaves no persistent log" >&2
    fi
    if ! is_regular_file "$STATUS_FILE"; then
        echo "Warning: ${STATUS_FILE} is not a regular file; backup state will not be recorded" >&2
    elif ! ( : >> "$STATUS_FILE" ) 2>/dev/null; then
        echo "Warning: cannot write ${STATUS_FILE}; backup state will not be recorded" >&2
    fi
}

# Restore-drill scratch paths. These are global on purpose: an EXIT trap runs
# after the function has returned, so a `local` would already be unset and the
# cleanup would silently delete nothing, leaving a full copy in /tmp.
RESTORE_TMP_DIR=""
RESTORE_BOOT_LOG=""
RESTORE_BOOT_PIPE=""
RESTORE_BOOT_READER=""

finish_restore_boot_log() {
    local attempt=0
    [ -n "$RESTORE_BOOT_READER" ] || return 0
    # The reader normally reaches EOF as soon as Vaultwarden exits. Do not let a
    # child that inherited the pipe keep the restore path blocked forever.
    while kill -0 "$RESTORE_BOOT_READER" 2>/dev/null; do
        if [ "$attempt" -ge 50 ]; then
            kill "$RESTORE_BOOT_READER" 2>/dev/null || :
            break
        fi
        sleep 0.1
        attempt=$((attempt + 1))
    done
    wait "$RESTORE_BOOT_READER" 2>/dev/null || :
    RESTORE_BOOT_READER=""
}

cleanup_restore_tmp() {
    finish_restore_boot_log
    [ -n "$RESTORE_TMP_DIR" ] && rm -rf "$RESTORE_TMP_DIR"
    [ -n "$RESTORE_BOOT_LOG" ] && rm -f "$RESTORE_BOOT_LOG"
    [ -n "$RESTORE_BOOT_PIPE" ] && rm -f "$RESTORE_BOOT_PIPE"
    # Bash keeps an EXIT trap set after the function that armed it returns, so
    # the same cleanup runs a second time at script exit. Clearing the paths
    # makes that second pass a no-op instead of a second recursive delete.
    RESTORE_TMP_DIR=""
    RESTORE_BOOT_LOG=""
    RESTORE_BOOT_PIPE=""
    RESTORE_BOOT_READER=""
    return 0
}

# Run a command, cap its bounded tail and show that tail only when requested or
# when the command fails. Keeping one capture path also means a future call site
# cannot accidentally opt out of redaction.
run_command() {
    local show_success="$1" label="$2" timeout_seconds="$3" out_file raw_file rc
    shift 3
    CURRENT_STEP="$label"
    out_file="$(mktemp "${TMPDIR:-/tmp}/restic-run.XXXXXX")" \
        || die "Unable to create temporary output file"
    raw_file="$(mktemp "${TMPDIR:-/tmp}/restic-raw.XXXXXX")" \
        || { rm -f "$out_file"; die "Unable to create temporary output file"; }
    printf '%s' "$(redact_raw "${B}${label}${X} ")" | tee -a "$LOG"
    # Cap the captured stream at 8x the retained log size, so a runaway command
    # cannot fill the disk before the tail truncation runs. The cap belongs on
    # the stream: `ulimit -f` bounded every file the command wrote as well, so
    # the SQLite hot copy died with SIGXFSZ once the database outgrew it and
    # `restic restore` answered "file too large" for any attachment above the
    # same size, which is the one path that has to work during a recovery.
    local raw_limit=$((MAX_LOG_BYTES * 8))
    rc=0
    (
        # `tail` is the other half of the pipeline, so it needs the backup lock
        # closed here; `timed` does the same for the command itself.
        exec 9>&-
        timed "$timeout_seconds" "$@" 2>&1 | tail -c "$raw_limit" > "$raw_file"
    ) || rc=$?
    if ! tail -c "$MAX_LOG_BYTES" "$raw_file" > "$out_file"; then
        rm -f "$raw_file" "$out_file" || :
        die "Unable to read the bounded command output"
    fi
    rm -f "$raw_file" || log echo -e "${Y}Warning: cannot remove temporary command output${X}"
    if [ "$rc" -eq 0 ]; then
        log echo -e "${G}✓${X}"
        if [ "$show_success" = true ] && [ -s "$out_file" ]; then
            log_result 0 cat "$out_file"
        fi
        rm -f "$out_file" || log echo -e "${Y}Warning: cannot remove temporary command output${X}"
        return 0
    fi
    log echo -e "${R}✗${X}"
    if [ -s "$out_file" ]; then
        log echo "[output capped at ${MAX_LOG_BYTES} bytes]"
        log redact_file "$out_file"
    fi
    rm -f "$out_file" || log echo -e "${Y}Warning: cannot remove temporary command output${X}"
    exit 2
}

run() { run_command false "$@"; }

# The snapshots command used to bypass run(), so an unbounded backend response
# reached the container log with the repository URL or credentials intact.
run_visible() { run_command true "$@"; }

sqlite_integrity_check() {
    local label="$1" database="$2"
    # shellcheck disable=SC2016  # Positional parameters belong to bash -c.
    run "$label" "$QUICK_TIMEOUT" bash -c '
        set -o pipefail
        sqlite3 "$1" "PRAGMA integrity_check" | awk "$2"
    ' sqlite "$database" "$SQLITE_INTEGRITY_AWK"
}

# ── Business Logic ────────────────────────────────────────────────────────────

# The image ships BusyBox find, which supports no GNU printf-format predicate: a
# size or mtime query that relies on one fails silently and turns the directory
# cap into a no-op. stat -c is available in the same BusyBox.
log_dir_size() {
    local sizes
    # A read that failed is not an empty directory: falling back to "0 bytes"
    # turned an unreadable log directory into a silent breach of the cap.
    sizes="$(find "$LOG_DIR" -maxdepth 1 -type f ! -name backup.lock \
        -exec stat -c '%s' {} + 2>/dev/null)" || return 2
    printf '%s\n' "$sizes" | awk '{total += $1} END {print total + 0}'
}

# Drop logs older than 10 hours, cap oversized files, then trim the directory.
# Any failed deletion or truncation is a warning, even when the directory as a
# whole is still below its cap: otherwise a per-file limit can fail silently.
trim_logs() {
    local file size tmp total failed=0
    if ! find "$LOG_DIR" -maxdepth 1 -type f \
        \( -name '*.log' -o -name '*.log.tmp.*' \) \
        -mmin +600 ! -path "$LOG" -delete; then
        echo "Warning: could not remove expired logs from ${LOG_DIR}" >&2
        failed=1
    fi
    for file in "$LOG_DIR"/*.log; do
        [ -f "$file" ] || continue
        if ! size="$(wc -c < "$file")"; then
            echo "Warning: cannot enforce the per-file log cap for ${file}" >&2
            failed=1
            continue
        fi
        if [ "$size" -gt "$MAX_LOG_BYTES" ]; then
            tmp="${file}.tmp.$$"
            if tail -c "$MAX_LOG_BYTES" "$file" > "$tmp"; then
                if ! mv "$tmp" "$file"; then
                    echo "Warning: cannot replace oversized log ${file}" >&2
                    rm -f "$tmp"
                    failed=1
                fi
            else
                echo "Warning: cannot enforce the per-file log cap for ${file}" >&2
                rm -f "$tmp"
                failed=1
            fi
        fi
    done
    if ! total="$(log_dir_size)"; then
        echo "Warning: cannot read ${LOG_DIR}; the log directory cap was not checked" >&2
        return 1
    fi
    if [ "$total" -gt "$MAX_LOG_DIR_BYTES" ]; then
        while IFS= read -r file; do
            [ -e "$file" ] || continue
            [ "$file" = "$LOG" ] && continue
            if ! size="$(stat -c '%s' "$file")"; then
                echo "Warning: cannot size log ${file} while trimming ${LOG_DIR}" >&2
                failed=1
                continue
            fi
            if rm -f "$file"; then
                total=$(( total - size ))
                [ "$total" -le "$MAX_LOG_DIR_BYTES" ] && break
            else
                echo "Warning: cannot remove log ${file} while trimming ${LOG_DIR}" >&2
                failed=1
            fi
        # Include interrupted *.log.tmp.* rewrites in the cap. Only delete files
        # this script owns; an unrelated file can trigger the warning above but
        # must never be removed by log maintenance.
        done < <(find "$LOG_DIR" -maxdepth 1 -type f \
            \( -name '*.log' -o -name '*.log.tmp.*' \) ! -path "$LOG" \
            -exec stat -c '%Y %n' {} + 2>/dev/null \
            | sort -n | cut -d' ' -f2-)
    fi
    if [ "$total" -gt "$MAX_LOG_DIR_BYTES" ]; then
        echo "Warning: log directory holds ${total} bytes, above the ${MAX_LOG_DIR_BYTES} byte cap and could not be trimmed" >&2
        return 1
    fi
    if [ "$failed" -ne 0 ]; then
        echo "Warning: log maintenance could not enforce every retention or file-size limit in ${LOG_DIR}" >&2
        return 1
    fi
    return 0
}

# Backup, check and prune
backup() {
    trap 'rc=$?; if [ "${rc:-0}" -ne 0 ] && [ "${rc:-0}" -ne 3 ]; then
        write_status failed "Task failed: ${CURRENT_STEP:-backup} (exit ${rc})"
        send_telegram "Task Failed: ${CURRENT_STEP:-backup}"
        heartbeat fail
    fi' EXIT

    # Skip instead of fighting over the repository when a manual run is already
    # active. A lock that cannot be created is an operational failure, not a
    # concurrent run: treating both as exit 3 hid a broken log directory behind
    # the one exit code the backup trap deliberately does not alert.
    if ! exec 9>"$LOG_DIR/backup.lock"; then
        echo "Cannot create ${LOG_DIR}/backup.lock" >&2
        # The EXIT trap owns status writes and alerts for every exit other than 3.
        CURRENT_STEP="Cannot create backup lock"
        exit 2
    fi
    if ! flock -n 9; then
        log echo -e "${Y}Another backup is already running, skipping this run${X}"
        exit 3
    fi

    # Only the run that owns the lock may publish "running": a skipped run that
    # wrote it first would erase the state the live run is maintaining.
    if ! write_status running "Backup started"; then
        echo "Cannot record backup start state" >&2
        CURRENT_STEP="Cannot record backup start state"
        exit 2
    fi

    # Initialise only when the repository really is missing (restic exit code 10).
    # A wrong password (12) or an unreachable backend (1) must be reported as such,
    # otherwise "restic init" answers with a misleading "already initialized" error.
    timed "$QUICK_TIMEOUT" restic cat config >/dev/null 2>&1 && rc=0 || rc=$?
    case "${rc:-1}" in
        0)  ;;
        10) log echo -e "${Y}Repository not initialized, initializing...${X}"
            run "Repo init" "$QUICK_TIMEOUT" restic init ;;
        *)  run "Repository access" "$QUICK_TIMEOUT" restic cat config ;;
    esac
    # Read-only repository access above distinguishes a fresh repository from a
    # bad credential or backend before cleanup. Only now can unlock failure be
    # treated as an unknown lock state that must stop the backup.
    clear_stale_locks

    # SQLite hot backup (ensures consistency)
    run "SQLite backup" "$QUICK_TIMEOUT" sqlite3 "$DATA/db.sqlite3" ".backup $DATA/backup.bak"
    sqlite_integrity_check "SQLite check" "$DATA/backup.bak"

    # Restic treats a bare glob as "at any depth", which silently dropped user
    # attachments named db.* or backup-status.txt. Anchor every exclusion at the
    # data root and name the SQLite files exactly so unrelated user files stay in
    # the snapshot.
    local backup_excludes=(
        --exclude="$DATA/db.sqlite3"
        --exclude="$DATA/db.sqlite3-journal"
        --exclude="$DATA/db.sqlite3-shm"
        --exclude="$DATA/db.sqlite3-wal"
        --exclude="$DATA/icon_cache"
        --exclude="$DATA/backup-status.txt"
    )
    case "$LOG_DIR" in
        "$DATA"/*) backup_excludes+=(--exclude="$LOG_DIR") ;;
    esac
    run "Data backup" "$LONG_TIMEOUT" restic backup --verbose \
        "${backup_excludes[@]}" "$DATA"
    run "Health check" "$LONG_TIMEOUT" restic check
    run "Snapshot prune" "$LONG_TIMEOUT" restic forget \
        --keep-hourly 24 --keep-daily 7 --keep-weekly 4 --keep-monthly 3 --keep-yearly 3 --prune

    local trim_message=""
    trim_logs || trim_message=" (log trim failed)"

    LAST_SUCCESS="$(date -u +%s)"
    if ! write_status ok "Backup complete${trim_message}"; then
        echo "Cannot record backup completion state" >&2
        CURRENT_STEP="Cannot record backup completion state"
        exit 2
    fi
    log echo -e "${G}Backup process complete ✨${X}"
    # Every hourly alert — success or failure — stays on Telegram. Repeating an
    # email 24 times a day trains the operator to filter it, so email is kept
    # for the monthly integrity check only.
    if [ -n "$trim_message" ]; then
        heartbeat fail
        send_telegram "Backup succeeded with warnings" || :
    else
        heartbeat ok
        if [ "$NOTIFY_ON_SUCCESS" = "true" ]; then
            send_telegram "Backup succeeded" || :
        fi
    fi
}

# Restore data from snapshot
restore() {
    [ -z "${1:-}" ] && { echo "Usage: $0 restore <snapshot-id>"; exit 1; }
    # `restic restore --target /` writes straight over the live /data while
    # Vaultwarden holds db.sqlite3 open, so a single keystroke between `restore`
    # and `restore-test` can destroy the running instance. Keep the destructive
    # path behind an explicit confirmation instead of one typo away.
    if [ "${RESTORE_CONFIRM:-}" != "yes" ]; then
        echo "Refusing to overwrite /data without RESTORE_CONFIRM=yes" >&2
        echo "Run 'restore-test' to verify a snapshot first, or confirm the in-place restore on purpose." >&2
        exit 2
    fi
    clear_stale_locks
    run "Restore snapshot $1" "$LONG_TIMEOUT" restic restore --target / -- "$1"
    # The snapshot carries the database as the consistent hot copy, not as the
    # live db.* files, so the command above leaves the old database in place.
    # Say so, or the operator walks away from a half-restored instance whose
    # keys were rolled back while its data was not.
    log echo -e "${Y}The live db.* files are not in the snapshot; the consistent copy is /data/backup.bak.${X}"
    log echo "To finish: 'touch /data/restore-pending', then restart the machine; the entrypoint swaps backup.bak in before Vaultwarden starts."
}

# Restore a snapshot into a temporary directory and validate the important files
restore_test() {
    local snapshot="${1:-latest}" tmp_parent free_bytes free_kb needed_bytes table stats_json
    tmp_parent="${TMPDIR:-/tmp}"
    [ -n "$tmp_parent" ] && [ -d "$tmp_parent" ] || tmp_parent=/tmp
    # The README promises the dead-man's-switch ping covers the drill and uses
    # the /fail URL when the run fails. Only the failure ping was missing, so a
    # broken drill left the switch armed as if nothing had run. Cleanup and the
    # alerts share one trap so they cannot drift apart.
    #
    # The ping is optional, so it cannot be the only channel: with
    # HEALTHCHECK_URL unset a failed drill reached nobody while the monthly
    # verify beside it emailed and notified Telegram. A drill that fails is the
    # one warning that the snapshots cannot be restored, so record the state and
    # use the rare (email + Telegram) channel too.
    trap 'rc=$?
        cleanup_restore_tmp
        if [ "${rc:-0}" -ne 0 ]; then
            write_guard_status failed "Restore drill failed (exit ${rc})"
            notify_rare "Restore drill failed"
            heartbeat fail
        fi' EXIT

    # Arm cleanup before creating either path. Otherwise a successful directory
    # allocation followed by a failed boot-log allocation leaves a full restored
    # snapshot behind, with no trap left to remove it.
    RESTORE_TMP_DIR="$(mktemp -d "$tmp_parent/restic-restore.XXXXXX")" \
        || die "Unable to create restore scratch directory"
    RESTORE_BOOT_LOG="$(mktemp "$tmp_parent/restic-boot.XXXXXX")" \
        || die "Unable to create restore scratch file"
    RESTORE_BOOT_PIPE="$RESTORE_TMP_DIR/restore-boot.fifo"
    if ! mkfifo "$RESTORE_BOOT_PIPE"; then
        die "Unable to create restore boot-log pipe"
    fi
    # Vaultwarden can emit an arbitrary amount of output before it fails. Keep
    # the temporary file at the same bounded tail size as every other command
    # diagnostic, rather than allowing a crash loop to fill /tmp.
    tail -c "$MAX_LOG_BYTES" < "$RESTORE_BOOT_PIPE" > "$RESTORE_BOOT_LOG" &
    RESTORE_BOOT_READER=$!
    local target="$RESTORE_TMP_DIR" boot_log="$RESTORE_BOOT_LOG"

    clear_stale_locks
    # Sizing has three distinct outcomes: a real number, a successful response
    # without total_size, and a failed read. Treating either failure mode as
    # zero bytes made the drill proceed without knowing whether it had space.
    if ! stats_json="$(
        timed "$QUICK_TIMEOUT" restic stats --json -- "$snapshot" 2>&1 \
            | tail -c "$MAX_LOG_BYTES"
    )"; then
        log echo -e "${R}Unable to size snapshot ${snapshot}${X}"
        [ -n "$stats_json" ] && log redact_raw "$stats_json"
        exit 2
    fi
    needed_bytes="$(printf '%s\n' "$stats_json" \
        | sed -n 's/.*"total_size": *\([0-9][0-9]*\).*/\1/p' | head -n 1)"
    case "$needed_bytes" in
        ''|*[!0-9]*)
            log echo -e "${R}Unable to size snapshot ${snapshot}${X}"
            [ -n "$stats_json" ] && log redact_raw "$stats_json"
            exit 2
            ;;
    esac
    case "$needed_bytes" in
        0|[1-9]|[1-9][0-9]*) ;;
        *)
            log echo -e "${R}Unable to use snapshot ${snapshot}: unusable snapshot size${X}"
            exit 2
            ;;
    esac
    if [ "${#needed_bytes}" -gt 16 ]; then
        log echo -e "${R}Unable to use snapshot ${snapshot}: unusable snapshot size${X}"
        exit 2
    fi
    # A failed df is not a zero-byte volume: keep the two failure modes apart so
    # the drill names the real cause instead of claiming the disk is full.
    if ! free_kb="$(df -Pk "$tmp_parent" | awk 'NR == 2 {print $4}')"; then
        log echo -e "${R}Unable to read free space for the restore drill${X}"
        exit 2
    fi
    case "$free_kb" in
        ''|*[!0-9]*)
            log echo -e "${R}Unable to read free space for the restore drill${X}"
            exit 2
            ;;
    esac
    if [ "${#free_kb}" -gt 15 ]; then
        log echo -e "${R}Unable to read free space for the restore drill${X}"
        exit 2
    fi
    free_bytes=$((free_kb * 1024))
    needed_bytes=$((needed_bytes + needed_bytes / 5 + 67108864))
    if [ "$free_bytes" -lt "$needed_bytes" ]; then
        log echo -e "${R}Not enough free space for the restore drill${X}"
        log echo "available=${free_bytes} required=${needed_bytes}"
        exit 2
    fi

    run "Restore drill" "$LONG_TIMEOUT" restic restore --target "$target" -- "$snapshot"
    if [ ! -f "$target/data/backup.bak" ] || [ ! -f "$target/data/rsa_key.pem" ]; then
        log echo -e "${R}Restore drill is missing expected files${X}"
        exit 2
    fi
    sqlite_integrity_check "Restore SQLite check" "$target/data/backup.bak"
    if ! sqlite3 "$target/data/backup.bak" ".tables" 2>/dev/null | grep -q .; then
        log echo -e "${R}Restored database has no tables${X}"
        exit 2
    fi

    # The snapshot leaves the live db.* files out on purpose and carries the
    # consistent hot copy instead, so the drill has to put that copy where
    # Vaultwarden looks. Booting a data directory with no database proved
    # nothing: Vaultwarden creates a fresh one and answers /alive anyway.
    cp "$target/data/backup.bak" "$target/data/db.sqlite3"
    for table in __diesel_schema_migrations users; do
        if ! sqlite3 "$target/data/db.sqlite3" \
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='${table}'" \
            | grep -q 1; then
            log echo -e "${R}The restored database is missing the ${table} table${X}"
            exit 2
        fi
    done
    # A marker in the restored file, so the boot below has to prove it opened
    # this database instead of quietly creating another one.
    sqlite3 "$target/data/db.sqlite3" \
        "CREATE TABLE IF NOT EXISTS drill_sentinel(v TEXT); DELETE FROM drill_sentinel; INSERT INTO drill_sentinel VALUES('restore-drill');"
    if ! printf '{"signups_allowed": false}\n' > "$target/restore-drill-config.json"; then
        log echo -e "${R}Unable to write the restore drill config${X}"
        exit 2
    fi

    log echo -e "${B}Restore cold boot${X} "
    if (
        cd "$target"
        boot_pid=""
        trap '[ -n "${boot_pid:-}" ] && kill "$boot_pid" 2>/dev/null || :' EXIT
        DATA_FOLDER="$target/data" WEB_VAULT_ENABLED=false \
            ROCKET_ADDRESS=127.0.0.1 ROCKET_PORT=18081 \
            CONFIG_FILE="$target/restore-drill-config.json" \
            /vaultwarden > "$RESTORE_BOOT_PIPE" 2>&1 &
        boot_pid=$!
        boot_alive() {
            [ -r "/proc/$boot_pid/stat" ] \
                && [ "$(awk '{print $3}' "/proc/$boot_pid/stat")" != "Z" ]
        }
        boot_ok=0
        for _ in $(seq 1 60); do
            boot_alive || break
            if wget -qO- http://127.0.0.1:18081/alive >/dev/null 2>&1 \
                && sleep 1 \
                && boot_alive; then
                    boot_ok=1
                    break
            fi
            sleep 0.5
        done
        kill "$boot_pid" 2>/dev/null || true
        wait "$boot_pid" 2>/dev/null || true
        boot_pid=""
        [ "$boot_ok" = "1" ]
    ); then
        finish_restore_boot_log
        log echo -e "${G}✓${X}"
        if [ "$(sqlite3 "$target/data/db.sqlite3" 'SELECT v FROM drill_sentinel' 2>/dev/null)" = "restore-drill" ]; then
            log echo -e "${G}The cold boot kept the restored database${X}"
        else
            log echo -e "${R}The cold boot did not keep the restored database${X}"
            exit 2
        fi
    else
        finish_restore_boot_log
        log echo -e "${R}✗${X}"
        log redact_file "$boot_log"
        exit 2
    fi
    log echo -e "${G}Restore drill complete${X}"
    heartbeat ok
}

# Read back a slice of the stored data to prove the repository is really readable
verify() {
    # This is the only job that looks for repository damage, and it used to exit
    # 2 with nothing but a log line: corruption waited for someone to read the
    # container log. Alert the way the backup does instead.
    trap 'rc=$?; if [ "${rc:-0}" -ne 0 ]; then
        write_guard_status failed "Repository verification failed (exit ${rc})"
        notify_rare "Repository verification failed"
        heartbeat fail
    fi' EXIT
    clear_stale_locks
    # Wait for a running backup instead of failing: the monthly check used to
    # fire at the same minute as the hourly backup, and restic refuses to take
    # an exclusive lock without --retry-lock.
    run "Repository data verification" "$LONG_TIMEOUT" restic check \
        --read-data-subset="${VERIFY_SUBSET:-10%}" --retry-lock="${VERIFY_RETRY_LOCK:-10m}"
    heartbeat ok
}

# Alert when the newest successful backup is older than BACKUP_MAX_AGE. The
# backup's own trap already covers a backup that runs and breaks; this covers one
# that silently stops running while the scheduler is still alive. A scheduler
# that has stopped entirely still needs HEALTHCHECK_URL, an external service.
# Every branch here runs hourly, so the alert stays on Telegram.
check_freshness() {
    local limit="${BACKUP_MAX_AGE:-7200}" now age uptime_s lock_state active_backup=false
    now="$(date -u +%s)"

    # A run that was killed mid-flight leaves the status at "running" forever.
    # A readable, free lock proves the run stopped. An uninspectable lock is
    # unknown: keep the running marker, but fail closed and alert instead of
    # letting the hourly guard report success without evidence.
    if [ "$STATUS_STATE" = "running" ]; then
        backup_is_running
        lock_state=$?
        case "$lock_state" in
            0) active_backup=true ;;
            1) log echo -e "${R}The last backup started but never finished${X}"
               write_status failed "Backup did not finish"
               send_telegram "Backup did not finish"
               heartbeat fail
               exit 2 ;;
            2)
                log echo -e "${R}Cannot inspect the backup lock; backup freshness is unknown${X}"
                # Preserve state=running as evidence, but record the guard's
                # failure in the message. A stale timestamp is not enough to
                # claim the run finished, and silence is not a healthy result.
                write_guard_status failed "Cannot inspect the backup lock"
                send_telegram "Cannot inspect the backup lock"
                heartbeat fail
                exit 2
                ;;
        esac
    fi

    # A marker that cannot be read is not "no data"; it cannot prove anything
    # about freshness. Leave the file untouched so the reason is still visible
    # after the alert, and do not synthesize a zero timestamp.
    if [ "$STATUS_MARKER_ERROR" = "unreadable" ]; then
        log echo -e "${R}Cannot read ${STATUS_FILE}; backup freshness is unknown${X}"
        send_telegram "Backup marker is unreadable"
        heartbeat fail
        exit 2
    fi
    if [ "$STATUS_MARKER_ERROR" = "missing" ]; then
        log echo -e "${R}${STATUS_FILE} does not contain last_success${X}"
        send_telegram "Backup marker is missing last_success"
        heartbeat fail
        exit 2
    fi
    if [ "$STATUS_MARKER_ERROR" = "oversized" ]; then
        log echo -e "${R}${STATUS_FILE} exceeds ${MAX_STATUS_BYTES} bytes; backup freshness is unknown${X}"
        send_telegram "Backup marker is oversized"
        heartbeat fail
        exit 2
    fi
    if [ "$STATUS_MARKER_ERROR" = "not_regular" ]; then
        log echo -e "${R}${STATUS_FILE} is not a regular file; backup freshness is unknown${X}"
        send_telegram "Backup marker is not a regular file"
        heartbeat fail
        exit 2
    fi
    if [ "$STATUS_MARKER_ERROR" = "invalid" ]; then
        log echo -e "${R}${STATUS_FILE} has an unusable last_success value${X}"
        write_guard_status failed "last_success in ${STATUS_FILE} is not a number"
        send_telegram "Backup marker is unusable"
        heartbeat fail
        exit 2
    fi

    # A successful timestamp from the previous run does not make the latest run
    # successful. Treat a recorded failure as failed immediately, and reject an
    # unknown state instead of letting a malformed marker hide behind a recent
    # last_success. The initial marker is the one exception: state=unknown with
    # no success is how a new volume starts.
    case "$STATUS_STATE" in
        ok|running) ;;
        failed)
            log echo -e "${R}${STATUS_FILE} records state=failed; the latest operation failed and last_success is not sufficient evidence${X}"
            send_telegram "Backup state is failed"
            heartbeat fail
            exit 2
            ;;
        unknown)
            if [ "$LAST_SUCCESS" != "0" ]; then
                log echo -e "${R}${STATUS_FILE} has an unknown state but a recorded success${X}"
                send_telegram "Backup marker state is inconsistent"
                heartbeat fail
                exit 2
            fi
            ;;
        *)
            log echo -e "${R}${STATUS_FILE} has an unusable recorded state${X}"
            send_telegram "Backup marker state is unusable"
            heartbeat fail
            exit 2
            ;;
    esac

    # The last successful run predates the one currently in flight. Its age
    # cannot prove the active run stale: the lock is held and the marker still
    # says running. Wait for that run to finish rather than overwriting its
    # evidence and sending a false stale alert.
    if [ "$active_backup" = true ]; then
        log echo -e "${Y}Backup is still running; skipping the last-success age check${X}"
        return 0
    fi

    if [ "$LAST_SUCCESS" = "0" ]; then
        # A fresh volume has no baseline yet, so only complain once the instance
        # has been up longer than the limit. A failed uptime read is unknown,
        # not a brand-new instance: treating it as zero silently disabled the
        # only guard that catches a backup which has never run.
        if ! uptime_s="$(cut -d. -f1 /proc/uptime)"; then
            uptime_s=""
        fi
        case "$uptime_s" in
            ''|*[!0-9]*)
                log echo -e "${R}Cannot determine the instance age${X}"
                write_guard_status failed "Cannot determine the instance age"
                send_telegram "Cannot determine the instance age"
                heartbeat fail
                exit 2
                ;;
        esac
        if [ "$uptime_s" -lt "$limit" ]; then
            log echo -e "${Y}No backup recorded yet and this instance is ${uptime_s}s old${X}"
            return 0
        fi
    fi
    age=$((now - LAST_SUCCESS))
    # A marker stamped in the future is not a fresh backup: the clock moved
    # backwards or the file was corrupted. Subtracting it produced a negative
    # age that passed the test below and printed "was -86400s ago" as if the
    # backup were healthy, which is the one reading that must never pass.
    if [ "$age" -lt 0 ]; then
        log echo -e "${R}Last successful backup is stamped in the future (${age}s); the clock or ${STATUS_FILE} cannot be trusted${X}"
        write_guard_status failed "last_success is in the future (${age}s)"
        send_telegram "Backup marker is in the future"
        heartbeat fail
        exit 2
    fi
    if [ "$age" -le "$limit" ]; then
        log echo -e "${G}Last successful backup was ${age}s ago (limit ${limit}s)${X}"
        return 0
    fi
    log echo -e "${R}Last successful backup was ${age}s ago (limit ${limit}s)${X}"
    write_status failed "No successful backup for ${age}s"
    send_telegram "Backup stale"
    heartbeat fail
    exit 2
}

# Alert before the data volume fills. The log directory has its own cap, but the
# volume also holds attachments, the icon cache and the database, and the
# snapshot's total size grows with them. A Fly volume is grown by migrating the
# data rather than in place, so the operator needs the warning while there is
# still room instead of once Vaultwarden's writes start failing.
check_disk() {
    local limit="${BACKUP_MAX_USAGE_PERCENT:-85}" used_percent
    used_percent="$(df -P "$DATA" 2>/dev/null | awk 'NR == 2 {gsub(/%/, "", $5); print $5}')"
    # Three states, not two: a reading that never arrived is not a healthy
    # volume. Reading it as one leaves the guard quietly guarding nothing.
    case "$used_percent" in
        ''|*[!0-9]*)
            log echo -e "${R}Cannot read the usage of ${DATA}${X}"
            write_guard_status failed "Cannot read the usage of ${DATA}"
            send_telegram "Cannot read the usage of ${DATA}"
            heartbeat fail
            exit 2
            ;;
    esac
    if [ "$used_percent" -lt "$limit" ]; then
        log echo -e "${G}${DATA} is ${used_percent}% full (limit ${limit}%)${X}"
        return 0
    fi
    log echo -e "${R}${DATA} is ${used_percent}% full (limit ${limit}%)${X}"
    write_guard_status failed "Data volume is ${used_percent}% full"
    send_telegram "Data volume is ${used_percent}% full"
    heartbeat fail
    exit 2
}

# Report the local recovery controls without changing backup state. This is the
# fixed read-only entry used by the production audit dispatch: it checks the
# persistent log directory, status marker, ownership, permissions, volume space
# and backup freshness in one bounded run.
audit() {
    local failed=0 file_count log_bytes bad_files dir_meta status_meta check_status
    local used_percent available_kb marker_state now age detail

    record_audit() {
        local result="$1" label="$2" detail="$3"
        if [ "$result" -eq 0 ]; then
            log echo -e "${G}✓ ${label}: ${detail}${X}"
        else
            failed=$((failed + 1))
            log echo -e "${R}✗ ${label}: ${detail}${X}"
        fi
    }

    if [ -L "$LOG_DIR" ] || [ ! -d "$LOG_DIR" ]; then
        record_audit 1 "log directory" "not a real directory"
    else
        if dir_meta="$(stat -c '%U %a' "$LOG_DIR" 2>/dev/null)"; then
            if [ "$dir_meta" = "vaultwarden 700" ]; then
                check_status=0
            else
                check_status=1
            fi
            record_audit "$check_status" "log directory" "owner/mode=${dir_meta}"
        else
            record_audit 1 "log directory" "metadata unreadable"
        fi

        if log_bytes="$(log_dir_size)"; then
            if [ "$log_bytes" -le "$MAX_LOG_DIR_BYTES" ]; then
                check_status=0
            else
                check_status=1
            fi
            record_audit "$check_status" "log bytes" "${log_bytes}/${MAX_LOG_DIR_BYTES}"
        else
            record_audit 1 "log bytes" "unreadable"
        fi

        if file_count="$(find "$LOG_DIR" -maxdepth 1 -type f ! -name backup.lock -print | wc -l)"; then
            record_audit 0 "log files" "$file_count"
        else
            record_audit 1 "log files" "unreadable"
        fi

        if bad_files="$(find "$LOG_DIR" -maxdepth 1 -type f \
            -exec stat -c '%U %a' {} + 2>/dev/null \
            | awk '$1 != "vaultwarden" || $2 != "600" {count++} END {print count + 0}')"; then
            if [ "$bad_files" -eq 0 ]; then
                check_status=0
            else
                check_status=1
            fi
            record_audit "$check_status" "log ownership" "noncompliant=${bad_files}"
        else
            record_audit 1 "log ownership" "metadata unreadable"
        fi

        if [ -e "$LOG_DIR/backup.lock" ] && ! is_regular_file "$LOG_DIR/backup.lock"; then
            record_audit 1 "backup lock" "not a regular file"
        else
            record_audit 0 "backup lock" "regular-or-absent"
        fi
    fi

    if ! is_regular_file "$STATUS_FILE"; then
        record_audit 1 "status marker" "not a regular file"
    elif status_meta="$(stat -c '%U %a' "$STATUS_FILE" 2>/dev/null)"; then
        if [ "$status_meta" = "vaultwarden 600" ]; then
            check_status=0
        else
            check_status=1
        fi
        record_audit "$check_status" "status marker" "owner/mode=${status_meta}"
    else
        record_audit 1 "status marker" "metadata unreadable"
    fi

    marker_state="$STATUS_STATE"
    case "$STATUS_MARKER_ERROR:$marker_state" in
        :ok|:running) record_audit 0 "status state" "$marker_state" ;;
        ':failed' ) record_audit 1 "status state" "failed" ;;
        ':unknown' ) record_audit 1 "status state" "unknown" ;;
        :*) record_audit 1 "status state" "unusable" ;;
        *) record_audit 1 "status state" "unreadable" ;;
    esac

    now="$(date -u +%s)"
    if [ "$STATUS_MARKER_ERROR" != "" ] || [ "$LAST_SUCCESS" -eq 0 ]; then
        record_audit 1 "backup age" "no usable success timestamp"
    else
        age=$((now - LAST_SUCCESS))
        if [ "$age" -lt 0 ]; then
            record_audit 1 "backup age" "timestamp is in the future"
        else
            if [ "$age" -le "${BACKUP_MAX_AGE:-7200}" ]; then
                check_status=0
            else
                check_status=1
            fi
            record_audit "$check_status" "backup age" "${age}s/${BACKUP_MAX_AGE:-7200}s"
        fi
    fi

    if detail="$(df -Pk "$DATA" 2>/dev/null | awk 'NR == 2 {gsub(/%/, "", $5); print $5, $4}')"; then
        used_percent="${detail%% *}"
        available_kb="${detail#* }"
        case "${used_percent}${available_kb}" in
            ''|*[!0-9]*) record_audit 1 "volume space" "unreadable" ;;
            *)
                if [ "$used_percent" -lt "${BACKUP_MAX_USAGE_PERCENT:-85}" ]; then
                    check_status=0
                else
                    check_status=1
                fi
                record_audit "$check_status" "volume space" \
                    "used=${used_percent}% available=${available_kb}KiB"
                ;;
        esac
    else
        record_audit 1 "volume space" "unreadable"
    fi

    if [ "$failed" -ne 0 ]; then
        log echo -e "${R}Production audit failed (${failed} checks)${X}"
        exit 2
    fi
    log echo -e "${G}Production audit passed${X}"
}

